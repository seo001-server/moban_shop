import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const root = path.dirname(fileURLToPath(import.meta.url))
const adminRoot = path.join(root, '../admin-frontend')
const yaml = require(path.join(adminRoot, 'node_modules/yaml'))
const pkgRoot = path.join(adminRoot, 'node_modules/@fortawesome/fontawesome-free')
const ymlPath = path.join(pkgRoot, 'metadata/icons.yml')
const outPath = path.join(adminRoot, 'src/lib/iconLibrary.generated.ts')

if (!fs.existsSync(ymlPath)) {
  console.error('icons.yml not found. Run: cd admin-frontend && npm install @fortawesome/fontawesome-free')
  process.exit(1)
}

const icons = yaml.parse(fs.readFileSync(ymlPath, 'utf8'))
const entries = []

for (const [name, meta] of Object.entries(icons)) {
  if (!meta || typeof meta !== 'object') continue
  if (!Array.isArray(meta.styles) || !meta.styles.includes('solid')) continue
  if (!/^[a-z0-9-]+$/i.test(name)) continue
  const terms = Array.isArray(meta.search?.terms) ? meta.search.terms.map(String) : []
  entries.push({
    code: `fa-${name}`,
    label: String(meta.label ?? name),
    terms,
  })
}

entries.sort((a, b) => a.code.localeCompare(b.code))

const body = `// Generated by scripts/generate-fa-icon-library.mjs — do not edit manually.
// Font Awesome Free 6 solid icons (${entries.length} total).

export type FaIconEntry = {
  code: string
  label: string
  terms: string[]
}

export const FA_SOLID_ICONS: FaIconEntry[] = ${JSON.stringify(entries, null, 2)}
`

fs.writeFileSync(outPath, body, 'utf8')
console.log(`Wrote ${entries.length} solid icons to ${outPath}`)
